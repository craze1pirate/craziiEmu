    private static byte[] GenerateAtlas()
    {
        var data = new byte[AtlasWidth * AtlasHeight];
        // Ensure top-left pixel (U=0, V=0) is opaque white (255) for solid color rects
        data[0] = 255;

        Span<float> temp8x16 = stackalloc float[8 * 16];
        for (int c = 32; c < 127; c++)
        {
            int col = c % 16;
            int row = c / 16;
            int startX = col * GlyphWidth;
            int startY = row * GlyphHeight;

            byte[] glyph = GetFontBitmap((char)c);

            // Rasterize glyph into temporary 8x16 buffer
            temp8x16.Clear();
            for (int y = 0; y < 16 && y < glyph.Length; y++)
            {
                byte rowByte = glyph[y];
                for (int x = 0; x < 8; x++)
                {
                    if ((rowByte & (1 << (7 - x))) != 0)
                    {
                        temp8x16[y * 8 + x] = 1.0f;
                    }
                }
            }

            // Bilinear upscale 8x16 to GlyphWidth x GlyphHeight with anti-aliasing soften
            for (int gy = 0; gy < GlyphHeight; gy++)
            {
                float srcY = (gy / (float)GlyphHeight) * 16.0f;
                int y0 = Math.Clamp((int)MathF.Floor(srcY), 0, 15);
                int y1 = Math.Clamp(y0 + 1, 0, 15);
                float fy = srcY - y0;

                for (int gx = 0; gx < GlyphWidth; gx++)
                {
                    float srcX = (gx / (float)GlyphWidth) * 8.0f;
                    int x0 = Math.Clamp((int)MathF.Floor(srcX), 0, 7);
                    int x1 = Math.Clamp(x0 + 1, 0, 7);
                    float fx = srcX - x0;

                    float v00 = temp8x16[y0 * 8 + x0];
                    float v10 = temp8x16[y0 * 8 + x1];
                    float v01 = temp8x16[y1 * 8 + x0];
                    float v11 = temp8x16[y1 * 8 + x1];

                    float top = v00 + (v10 - v00) * fx;
                    float bottom = v01 + (v11 - v01) * fx;
                    float intensity = top + (bottom - top) * fy;

                    if (intensity > 0.05f)
                    {
                        byte alpha = (byte)Math.Clamp((int)(intensity * 255.0f * 1.4f), 0, 255);
                        int px = startX + gx;
                        int py = startY + gy;
                        if (px != 0 || py != 0) // Preserve solid white at 0,0
                        {
                            data[py * AtlasWidth + px] = alpha;
                        }
                    }
                }
            }
        }

        return data;
    }

